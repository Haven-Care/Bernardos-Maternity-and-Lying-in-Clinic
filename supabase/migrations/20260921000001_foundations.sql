-- ---------------------------------------------------------------------------
-- Foundations: enums, ID sequences, and shared helpers.
--
-- Every enum below mirrors a closed union in frontend/src/types/. Where the
-- contract leaves a union open with `(string & {})` — medicine category and
-- unit — the column stays `text`, because the design's own dropdowns allow
-- free entry there.
--
-- Two representation choices worth stating once, since every later migration
-- depends on them:
--
--   * Clock times are `text` matching 'HH:MM', not Postgres `time`. The
--     contract's TimeString is 'HH:mm' and `time` renders as '08:00:00', so
--     storing `time` would mean formatting on every read and one missed spot
--     showing "08:00:00" in the UI. Zero-padded 24-hour text sorts correctly
--     and compares correctly, which is all slots need.
--   * Dates are `date` and timestamps are `timestamptz`. PostgREST already
--     serialises those as 'YYYY-MM-DD' and ISO 8601, matching DateString and
--     DateTimeString exactly.
-- ---------------------------------------------------------------------------

create type weekday as enum (
  'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'
);

