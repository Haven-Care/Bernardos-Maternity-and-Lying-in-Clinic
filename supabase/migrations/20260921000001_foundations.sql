-- Maps a date to a weekday.
--
-- Deliberately built on ISODOW rather than `to_char(d, 'Day')`: to_char's day
-- names come from the server's lc_time, so a locale change would silently
-- start returning names that fail the enum cast. ISODOW is 1=Monday..7=Sunday
-- everywhere, always.
create function weekday_of(d date) returns weekday
language sql
immutable
strict
as $$
  select (array[
    'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'
  ]::weekday[])[extract(isodow from d)::int];
$$;

-- ---------------------------------------------------------------------------
-- "Today", as the clinic means it.
--
-- The database runs in UTC and the clinic is in Caloocan City, UTC+8. For the
-- eight hours between Manila midnight and UTC midnight, `current_date` is
-- *yesterday* as far as the database is concerned — so Today's Schedule would
-- show the wrong day every evening, a booking for this morning would be
-- rejected as being in the past, and Days Left would be off by one.
--
-- Every business rule that needs a date uses this, not `current_date`.
-- ---------------------------------------------------------------------------
create function clinic_today() returns date
language sql
stable
as $$
  select (now() at time zone 'Asia/Manila')::date;
$$;

create function set_updated_at() returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Clock time as the contract spells it: zero-padded 24-hour 'HH:MM'.
create domain clock_time as text
  check (value ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$');
